function renderThemes(palettes, template) {
  const themes = {};
  const outputs = new Map();
  for (const [key, palette] of Object.entries(palettes)) {
    themes[key] = theme(palette);
    outputs.set(`themes/research-notes-${key}-color-theme.json`, JSON.stringify(themes[key], null, 2) + '\n');
  }
  outputs.set('preview.html', template.replace('/* THEME_DATA */', `const THEMES = ${JSON.stringify(themes)};`));
  return outputs;
}
